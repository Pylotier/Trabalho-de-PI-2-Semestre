    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
        try {
            ClassProduto cp = new ClassProduto();
            ClassEnderecoProduto cend = new ClassEnderecoProduto();
            ClassComerciante com = new ClassComerciante();

            cend.setCEP(txtCEP.getText());
            cend.setLogradouro(txtLogradouro.getText());
            cend.setNumero(Integer.parseInt(txtNumero.getText()));
            cend.setComplemento(txtAreaComplemento.getText());     

            cp.setNomeCategoria(txtCategoria.getText());

            cp.setNomeProduto(txtNomeProduto.getText());
            cp.setPreco(Float.parseFloat(txtPreco.getText()));
            cp.setQtdeDisponivel(Integer.parseInt(txtQtde.getText()));
            cp.setDescricao(tblDescricao.getText());
            
            int id  = Integer.parseInt(txtIDProduto.getText());

            com.AtualizarProtudo(cp, cend, id);

            JOptionPane.showMessageDialog(
                null,
                "Produto atualizados com sucesso!"
            );

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                null,
                e.getMessage(),
                "ERRO",
                JOptionPane.ERROR_MESSAGE
            );
        }

    }//GEN-LAST:event_btnAtualizarActionPerformed

