    private void btnBuscaProdutoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscaProdutoActionPerformed
        try {
            ClassProduto cp = new ClassProduto();
            ClassEnderecoProduto cend = new ClassEnderecoProduto();
            GenericDAO gDao = new GenericDAO();
            Connection conn = gDao.getConnection();
            
            int id  = Integer.parseInt(txtIDProduto.getText());

            String retornoProduto = "SELECT p.Nome AS Nome, p.Preco AS Preco, " +
            "p.Qtde_Disponivel AS Qtde, " +
            "p.Descricao AS Descricao, " +
            "ende.CEP AS CEP, ende.Logradouro " +
            "AS Logradouro, ende.Complemento " +
            "AS Complemento " +
            "FROM Produto AS p " +
            "INNER JOIN EnderecoEstoque AS ende " +
            "ON ende.ID = p.EnderecoEstoqueID " +
            "WHERE p.ID = ?";
            PreparedStatement psRetornaID = conn.prepareStatement(retornoProduto);
            psRetornaID.setInt(1, id);

            ResultSet rs = psRetornaID.executeQuery();

            if (rs.next()) {
                txtNomeProduto.setText(rs.getString("Nome"));
                txtPreco.setText(String.valueOf(rs.getFloat("Preco")));
                txtQtde.setText(String.valueOf(rs.getInt("Qtde")));
                tblDescricao.setText(rs.getString("Descricao"));
                txtCEP.setText(rs.getString("CEP"));
                txtLogradouro.setText(rs.getString("Logradouro"));
                txtAreaComplemento.setText(rs.getString("Complemento"));     
            }

            rs.close();
            psRetornaID.close();
        } catch(Exception e) {
            String exception = e.getMessage();
            JOptionPane.showMessageDialog(null,
                    exception,
                    "ERRO",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnBuscaProdutoActionPerformed

