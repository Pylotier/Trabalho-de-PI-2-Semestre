    private void listarTabela() {
        try {
            ClassCategoria ct = new ClassCategoria();
            List<ClassCategoria> lista = ct.findAllProduto();
            DefaultTableModel model = 
                    (DefaultTableModel)tblCateogoria.getModel();
            model.setRowCount(0);
            for (ClassCategoria ctLista : lista) {
                Object[] linha = new Object[2];
                linha[0] = ctLista.getID_Categoria();
                linha[1] = ctLista.getNomeCategoria();
                model.addRow(linha);
            }
        } catch(Exception e) {
            String exception = e.getMessage();
            JOptionPane.showMessageDialog(null,
                    exception,
                    "ERRO",
                    JOptionPane.ERROR_MESSAGE);
        }

    }

