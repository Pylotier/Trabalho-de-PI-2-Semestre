    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        
        try {
            // 1. Cadastra o cliente
            ClassAdministrador ca = new ClassAdministrador();

            String email = txtEmail.getText();
            String senha = txtSenha.getText();
            String usuario = txtUsuario.getText();

            ca.setEmail(email);
            ca.setSenha(senha);
            ca.setUsusario(usuario);

            int idAdministrador = ca.insertAdministrador(ca);

            // 2. Cria o carrinho utilizando o ID do cliente

            JOptionPane.showMessageDialog(
                null,
                "Cliente e carrinho cadastrados com sucesso!",
                "SUCESSO",
                JOptionPane.INFORMATION_MESSAGE
            );
            
            ca.iniciarSessao(idAdministrador);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(
                null,
                e.getMessage(),
                "ERRO",
                JOptionPane.ERROR_MESSAGE
            );
        }
        
        
        
    }//GEN-LAST:event_btnCadastrarActionPerformed

