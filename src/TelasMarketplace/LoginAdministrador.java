    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String email = txtEmail.getText();
       String senha = txtSenha.getText();
       
       ClassAdministrador ca = new ClassAdministrador();
       
       int id = ca.logIn(email, senha);
       
       try{
            if (id != 0){
                ca.iniciarSessao(id);
                JOptionPane.showMessageDialog(null, "Login realizado com sucesso!");
                System.out.print("id usuario:" + id);
                
                TelaAdministrador tela = new TelaAdministrador(id);
                
                tela.setVisible(true);
                this.dispose();
                
            }else{
                JOptionPane.showMessageDialog(null, "Campo(s) incorreto(s)");
            }    
       }catch (Exception e){
           JOptionPane.showMessageDialog(
                null,
                e.getMessage(),
                "ERRO",
                JOptionPane.ERROR_MESSAGE
            );
       }
       
       
    }//GEN-LAST:event_btnLoginActionPerformed

